const loudness = (sound, value) =>
    make_sound(t => get_wave(sound)(t) * value, get_duration(sound));

const ocarina_note = (midi, dur) =>
    adsr(0.01, 0.05, 0.7, 0.1)(
        triangle_sound(midi_note_to_frequency(midi), dur)
    );

const vocal_note = (midi, dur) =>
    adsr(0.02, 0.05, 0.8, 0.15)(
        square_sound(midi_note_to_frequency(midi), dur)
    );

const bass_guitar_note = (midi, dur) =>
    adsr(0.005, 0.05, 0.4, 0.05)(
        square_sound(midi_note_to_frequency(midi), dur)
    );

const kick = dur => {
  const base = sine_sound(60, dur);
  const pitched = phase_mod(240, dur, 3)(base);
  return adsr(0.001, 0.15, 0, 0.05)(pitched);
};

const snare = dur => {
    const tone = adsr(0.005, 0.2, 0, 0.05)(square_sound(200, dur));
    const noise = adsr(0.001, 0.2, 0, 0.05)(noise_sound(dur));
    return simultaneously(list(tone,noise));
};

const hihat_closed = dur => {
  const noise = adsr(0.001, 0.2, 0, 0.02)(noise_sound(dur));
  return noise;
};

const hihat_open = dur => {
  const noise = adsr(0.001, 0.7, 0, 0.1)(noise_sound(dur));
  return noise;
};

const percussion = (midi, dur) =>
    midi === 27
    ? loudness(kick(dur), 17)
    : midi === 38
    ? snare(dur)
    : midi === 44
    ? hihat_closed(dur)
    : midi === 46
    ? hihat_open(dur)
    : hihat_open(dur); // crash
    
